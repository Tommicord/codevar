//! Windows code-page family `12xx` text decoders.
//!
//! Covers:
//! - **1200** — UTF-16LE (with optional BOM `FF FE`)
//! - **1201** — UTF-16BE (with optional BOM `FE FF`)
//! - **1250..=1258** — Windows single-byte code pages (high-byte tables)
//!
//! Named `windows12xx` after the Windows code-page numbering for this family.

use crate::parse_common::{
    FormatParser, ParserError, ParserResult, Segment, SegmentKind, ValidationInfo,
};

/// Windows code page identifier in the 12xx family.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u16)]
pub enum Windows12xxCodePage {
    /// UTF-16 little-endian (code page 1200).
    Utf16Le = 1200,
    /// UTF-16 big-endian (code page 1201).
    Utf16Be = 1201,
    /// Central Europe.
    Cp1250 = 1250,
    /// Cyrillic.
    Cp1251 = 1251,
    /// Western European (most common ANSI).
    Cp1252 = 1252,
    /// Greek.
    Cp1253 = 1253,
    /// Turkish.
    Cp1254 = 1254,
    /// Hebrew.
    Cp1255 = 1255,
    /// Arabic.
    Cp1256 = 1256,
    /// Baltic.
    Cp1257 = 1257,
    /// Vietnamese.
    Cp1258 = 1258,
}

impl Windows12xxCodePage {
    /// Numeric Windows code-page id.
    #[must_use]
    pub const fn id(self) -> u16 {
        self as u16
    }

    /// Parses a numeric code-page id.
    #[must_use]
    pub const fn from_id(id: u16) -> Option<Self> {
        match id {
            1200 => Some(Self::Utf16Le),
            1201 => Some(Self::Utf16Be),
            1250 => Some(Self::Cp1250),
            1251 => Some(Self::Cp1251),
            1252 => Some(Self::Cp1252),
            1253 => Some(Self::Cp1253),
            1254 => Some(Self::Cp1254),
            1255 => Some(Self::Cp1255),
            1256 => Some(Self::Cp1256),
            1257 => Some(Self::Cp1257),
            1258 => Some(Self::Cp1258),
            _ => None,
        }
    }
}

/// Decoder for Windows 12xx code pages.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Windows12xxParser {
    /// Active code page.
    pub code_page: Windows12xxCodePage,
}

impl Windows12xxParser {
    /// Creates a parser for `code_page`.
    #[must_use]
    pub const fn new(code_page: Windows12xxCodePage) -> Self {
        Self { code_page }
    }

    /// UTF-16LE (1200).
    #[must_use]
    pub const fn utf16_le() -> Self {
        Self::new(Windows12xxCodePage::Utf16Le)
    }

    /// UTF-16BE (1201).
    #[must_use]
    pub const fn utf16_be() -> Self {
        Self::new(Windows12xxCodePage::Utf16Be)
    }

    /// Windows-1252.
    #[must_use]
    pub const fn cp1252() -> Self {
        Self::new(Windows12xxCodePage::Cp1252)
    }

    /// Detects 1200 / 1201 from BOM when present.
    #[must_use]
    pub fn detect_from_bom(data: &[u8]) -> Option<Windows12xxCodePage> {
        if data.len() >= 2 && data[0] == 0xFF && data[1] == 0xFE {
            Some(Windows12xxCodePage::Utf16Le)
        } else if data.len() >= 2 && data[0] == 0xFE && data[1] == 0xFF {
            Some(Windows12xxCodePage::Utf16Be)
        } else {
            None
        }
    }

    /// Decodes `data` to Unicode scalar values.
    ///
    /// # Errors
    ///
    /// Returns [`ParserError::DecodeError`] / [`ParserError::InsufficientData`]
    /// on truncated or invalid sequences.
    pub fn decode(self, data: &[u8]) -> ParserResult<Vec<char>> {
        match self.code_page {
            Windows12xxCodePage::Utf16Le => decode_utf16(data, true),
            Windows12xxCodePage::Utf16Be => decode_utf16(data, false),
            cp => decode_single_byte(data, high_map(cp)),
        }
    }

    /// Validates encoding shape (even length for UTF-16, full map for SBCS).
    ///
    /// # Errors
    ///
    /// Returns a parse error when the buffer cannot be decoded.
    pub fn validate_bytes(self, data: &[u8]) -> ParserResult<ValidationInfo> {
        let _ = self.decode(data)?;
        Ok(ValidationInfo::ok(format!(
            "valid Windows-{}",
            self.code_page.id()
        )))
    }

    /// Emits one [`SegmentKind::TextRun`] per decoded scalar (UTF-16) or byte (SBCS).
    ///
    /// # Errors
    ///
    /// Returns a parse error when decoding fails.
    pub fn segments(self, data: &[u8]) -> ParserResult<Vec<Segment>> {
        match self.code_page {
            Windows12xxCodePage::Utf16Le => segments_utf16(data, true),
            Windows12xxCodePage::Utf16Be => segments_utf16(data, false),
            cp => {
                let map = high_map(cp);
                let mut out = Vec::with_capacity(data.len());
                for (i, &b) in data.iter().enumerate() {
                    map_byte(b, map).map_err(|msg| {
                        ParserError::DecodeError(format!("{msg} at {i}"))
                    })?;
                    out.push(Segment::new(
                        SegmentKind::TextRun,
                        i,
                        1,
                        u32::from(cp.id()),
                    ));
                }
                Ok(out)
            }
        }
    }
}

impl FormatParser for Windows12xxParser {
    fn name() -> &'static str {
        "windows-12xx"
    }

    fn detect(data: &[u8]) -> bool {
        Self::detect_from_bom(data).is_some()
    }

    fn validate(data: &[u8]) -> ParserResult<ValidationInfo> {
        let cp = Self::detect_from_bom(data).ok_or_else(|| {
            ParserError::UnsupportedFileType("no Windows-12xx BOM".into())
        })?;
        Self::new(cp).validate_bytes(data)
    }

    fn segments(data: &[u8]) -> ParserResult<Vec<Segment>> {
        let cp = Self::detect_from_bom(data).ok_or_else(|| {
            ParserError::UnsupportedFileType("no Windows-12xx BOM".into())
        })?;
        Self::new(cp).segments(data)
    }
}

fn decode_utf16(data: &[u8], little: bool) -> ParserResult<Vec<char>> {
    let mut i = 0usize;
    // Skip BOM if present.
    if data.len() >= 2 {
        let b0 = data[0];
        let b1 = data[1];
        if (little && b0 == 0xFF && b1 == 0xFE) || (!little && b0 == 0xFE && b1 == 0xFF) {
            i = 2;
        }
    }
    if !(data.len() - i).is_multiple_of(2) {
        return Err(ParserError::DecodeError(
            "UTF-16 buffer has odd length".into(),
        ));
    }

    let mut units = Vec::new();
    while i + 1 < data.len() {
        let unit = if little {
            u16::from_le_bytes([data[i], data[i + 1]])
        } else {
            u16::from_be_bytes([data[i], data[i + 1]])
        };
        units.push(unit);
        i += 2;
    }

    let mut chars = Vec::new();
    let mut iter = units.iter().copied().peekable();
    while let Some(u) = iter.next() {
        if (0xD800..=0xDBFF).contains(&u) {
            let Some(low) = iter.next() else {
                return Err(ParserError::DecodeError(
                    "truncated UTF-16 surrogate pair".into(),
                ));
            };
            if !(0xDC00..=0xDFFF).contains(&low) {
                return Err(ParserError::DecodeError(
                    "invalid UTF-16 low surrogate".into(),
                ));
            }
            let cp = 0x1_0000 + ((u32::from(u - 0xD800) << 10) | u32::from(low - 0xDC00));
            match char::from_u32(cp) {
                Some(ch) => chars.push(ch),
                None => {
                    return Err(ParserError::DecodeError(
                        "invalid scalar from UTF-16 pair".into(),
                    ));
                }
            }
        } else if (0xDC00..=0xDFFF).contains(&u) {
            return Err(ParserError::DecodeError(
                "unexpected UTF-16 low surrogate".into(),
            ));
        } else {
            match char::from_u32(u32::from(u)) {
                Some(ch) => chars.push(ch),
                None => {
                    return Err(ParserError::DecodeError("invalid UTF-16 unit".into()));
                }
            }
        }
    }
    Ok(chars)
}

fn segments_utf16(data: &[u8], little: bool) -> ParserResult<Vec<Segment>> {
    let mut out = Vec::new();
    let mut i = 0usize;
    if data.len() >= 2 {
        let bom = (little && data[0] == 0xFF && data[1] == 0xFE)
            || (!little && data[0] == 0xFE && data[1] == 0xFF);
        if bom {
            out.push(Segment::new(SegmentKind::Signature, 0, 2, 0));
            i = 2;
        }
    }
    if !(data.len() - i).is_multiple_of(2) {
        return Err(ParserError::DecodeError(
            "UTF-16 buffer has odd length".into(),
        ));
    }
    while i + 1 < data.len() {
        let unit = if little {
            u16::from_le_bytes([data[i], data[i + 1]])
        } else {
            u16::from_be_bytes([data[i], data[i + 1]])
        };
        if (0xD800..=0xDBFF).contains(&unit) {
            if i + 3 >= data.len() {
                return Err(ParserError::InsufficientData);
            }
            out.push(Segment::new(SegmentKind::TextRun, i, 4, u32::from(unit)));
            i += 4;
        } else {
            out.push(Segment::new(SegmentKind::TextRun, i, 2, u32::from(unit)));
            i += 2;
        }
    }
    Ok(out)
}

fn decode_single_byte(data: &[u8], map: &[u16; 128]) -> ParserResult<Vec<char>> {
    let mut chars = Vec::with_capacity(data.len());
    for (i, &b) in data.iter().enumerate() {
        let cp = map_byte(b, map)
            .map_err(|e| ParserError::DecodeError(format!("{e} at {i}")))?;
        match char::from_u32(u32::from(cp)) {
            Some(ch) => chars.push(ch),
            None => {
                return Err(ParserError::DecodeError(format!(
                    "unmapped byte 0x{b:02X} at {i}"
                )));
            }
        }
    }
    Ok(chars)
}

fn map_byte(b: u8, map: &[u16; 128]) -> Result<u16, &'static str> {
    if b < 0x80 {
        Ok(u16::from(b))
    } else {
        let cp = map[usize::from(b - 0x80)];
        if cp == 0 {
            Err("undefined code-page byte")
        } else {
            Ok(cp)
        }
    }
}

fn high_map(cp: Windows12xxCodePage) -> &'static [u16; 128] {
    match cp {
        Windows12xxCodePage::Cp1250 => &CP1250,
        Windows12xxCodePage::Cp1251 => &CP1251,
        Windows12xxCodePage::Cp1252
        | Windows12xxCodePage::Utf16Le
        | Windows12xxCodePage::Utf16Be => &CP1252,
        Windows12xxCodePage::Cp1253 => &CP1253,
        Windows12xxCodePage::Cp1254 => &CP1254,
        Windows12xxCodePage::Cp1255 => &CP1255,
        Windows12xxCodePage::Cp1256 => &CP1256,
        Windows12xxCodePage::Cp1257 => &CP1257,
        Windows12xxCodePage::Cp1258 => &CP1258,
    }
}

