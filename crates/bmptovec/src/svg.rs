//! SVG serialization of a [`VectorDoc`].
//!
//! Faithful port of visioncortex/vtracer's `crates/vtracer/src/svg.rs`:
//! an `SvgWriter` that emits an SVG document with optional path-data shorthands
//! (axis-aligned H/V, smooth S, relative vs absolute shortest encoding) and
//! fill-grouping by color.

use crate::ir::{MultiPath, PathCmd, Shape, SubPath, VectorDoc};
use crate::types::PointF64;

/// The SVG writer: serializes a [`VectorDoc`] to an SVG string.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SvgWriter {
    /// Whether to use relative path commands where shorter.
    pub relative: bool,
    /// Whether to use path-data shorthands (H/V/h/v, S/s).
    pub shorthands: bool,
    /// Number of fractional digits to emit, or `None` for full precision.
    pub precision: Option<u32>,
}

impl Default for SvgWriter {
    fn default() -> Self {
        Self {
            relative: true,
            shorthands: true,
            precision: Some(3),
        }
    }
}

impl SvgWriter {
    /// Write the full SVG document for `doc`.
    pub fn write(&self, doc: &VectorDoc) -> String {
        let mut out = String::new();
        out.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        out.push_str("<!-- generated by codevar-bmptovec (visioncortex/vtracer port) -->\n");
        out.push_str(&format!(
            "<svg version=\"1.1\" xmlns=\"http://www.w3.org/2000/svg\" width=\"{}\" height=\"{}\">\n",
            doc.width, doc.height
        ));

        if self.shorthands {
            // Group consecutive shapes by fill color into `<g fill=...>` blocks.
            let mut i = 0;
            while i < doc.shapes.len() {
                let fill = shape_fill(&doc.shapes[i]);
                let mut j = i;
                while j < doc.shapes.len() && shape_fill(&doc.shapes[j]) == fill {
                    j += 1;
                }
                out.push_str(&format!("<g fill=\"{fill}\">\n"));
                for k in i..j {
                    out.push_str(&write_path(self, &doc.shapes[k].path));
                    out.push('\n');
                }
                out.push_str("</g>\n");
                i = j;
            }
        } else {
            for shape in &doc.shapes {
                let fill = shape_fill(shape);
                out.push_str(&format!(
                    "<path fill=\"{fill}\" d=\"{}\"/>\n",
                    write_path(self, &shape.path)
                ));
            }
        }

        out.push_str("</svg>\n");
        out
    }
}

/// The fill color (hex) of a shape.
#[inline]
fn shape_fill(shape: &Shape) -> String {
    match shape.paint {
        crate::ir::Paint::Solid(c) => c.to_hex_string(),
    }
}

/// Write the `d` attribute of a single multi-path.
#[inline]
fn write_path(writer: &SvgWriter, path: &MultiPath) -> String {
    let mut emitter = Emitter::new(writer.relative, writer.shorthands, writer.precision);
    for subpath in &path.subpaths {
        emitter.subpath(subpath);
    }
    emitter.finish()
}

/// Emitter state for encoding one multi-path into path data.
struct Emitter {
    /// Whether to use relative path commands where shorter.
    relative: bool,
    /// Whether to use path-data shorthands (H/V/h/v, S/s).
    shorthands: bool,
    precision: Option<u32>,
    /// Output buffer.
    out: String,
    /// Current point (absolute).
    cur: Option<PointF64>,
    /// Start point of the current subpath.
    start: Option<PointF64>,
    /// Previous cubic's second control point (for smooth S/s shorthand).
    prev_c2: Option<PointF64>,
}

impl Emitter {
    fn new(relative: bool, shorthands: bool, precision: Option<u32>) -> Self {
        Self {
            relative,
            shorthands,
            precision,
            out: String::new(),
            cur: None,
            start: None,
            prev_c2: None,
        }
    }

    /// Emit a complete subpath.
    fn subpath(&mut self, sp: &SubPath) {
        for cmd in &sp.commands {
            match cmd {
                PathCmd::MoveTo(p) => self.move_to(*p),
                PathCmd::LineTo(p) => self.line_to(*p),
                PathCmd::CubicTo(c1, c2, c3) => self.cubic_to(*c1, *c2, *c3),
                PathCmd::Close => self.close(),
            }
        }
    }

    /// Emit a move-to, starting a new subpath.
    fn move_to(&mut self, p: PointF64) {
        let abs = fmt_num(p.x, self.precision);
        let ord = fmt_num(p.y, self.precision);
        let cmd = if self.relative {
            if let Some(cur) = self.cur {
                let dx = p.x - cur.x;
                let dy = p.y - cur.y;
                let sx = fmt_num(dx, self.precision);
                let sy = fmt_num(dy, self.precision);
                let rel_cmd = format!("m{sx} {sy}");
                let abs_cmd = format!("M{abs} {ord}");
                if shorter(&rel_cmd, &abs_cmd) {
                    rel_cmd
                } else {
                    abs_cmd
                }
            } else {
                format!("M{abs} {ord}")
            }
        } else {
            format!("M{abs} {ord}")
        };
        self.out.push_str(&cmd);
        self.cur = Some(p);
        self.start = Some(p);
        self.prev_c2 = None;
    }

    /// Emit a line-to.
    fn line_to(&mut self, p: PointF64) {
        let last = self.cur.unwrap_or(PointF64::new(0.0, 0.0));
        let abs_x = fmt_num(p.x, self.precision);
        let abs_y = fmt_num(p.y, self.precision);

        // Axis-aligned H/V shorthands.
        if self.shorthands {
            if approx(p.y, last.y) {
                // horizontal
                let cmd = if self.relative {
                    let dx = p.x - last.x;
                    let sx = fmt_num(dx, self.precision);
                    // h vs H
                    if shorter(&sx, &abs_x) {
                        format!("h{sx}")
                    } else {
                        format!("H{abs_x}")
                    }
                } else {
                    format!("H{abs_x}")
                };
                self.out.push_str(&cmd);
                self.cur = Some(p);
                self.prev_c2 = None;
                return;
            }
            if approx(p.x, last.x) {
                // vertical
                let cmd = if self.relative {
                    let dy = p.y - last.y;
                    let sy = fmt_num(dy, self.precision);
                    if shorter(&sy, &abs_y) {
                        format!("v{sy}")
                    } else {
                        format!("V{abs_y}")
                    }
                } else {
                    format!("V{abs_y}")
                };
                self.out.push_str(&cmd);
                self.cur = Some(p);
                self.prev_c2 = None;
                return;
            }
        }

        let cmd = if self.relative {
            let dx = p.x - last.x;
            let dy = p.y - last.y;
            let sx = fmt_num(dx, self.precision);
            let sy = fmt_num(dy, self.precision);
            let ax = fmt_num(p.x, self.precision);
            let ay = fmt_num(p.y, self.precision);
            let rel_cmd = format!("l{sx} {sy}");
            let abs_cmd = format!("L{ax} {ay}");
            if shorter(&rel_cmd, &abs_cmd) {
                rel_cmd
            } else {
                abs_cmd
            }
        } else {
            format!("L{abs_x} {abs_y}")
        };
        self.out.push_str(&cmd);
        self.cur = Some(p);
        self.prev_c2 = None;
    }

    /// Emit a cubic-to.
    fn cubic_to(&mut self, c1: PointF64, c2: PointF64, c3: PointF64) {
        let last = self.cur.unwrap_or(PointF64::new(0.0, 0.0));

        // Smooth shorthand S/s when the first control point is the reflection
        // of the previous cubic's second control point.
        let smooth = self.shorthands
            && self
                .prev_c2
                .is_some_and(|prev_c2| approx_pt(c1, reflect(last, prev_c2)));

        if smooth {
            let cmd = if self.relative {
                let sx1 = fmt_num(c2.x - last.x, self.precision);
                let sy1 = fmt_num(c2.y - last.y, self.precision);
                let sx2 = fmt_num(c3.x - last.x, self.precision);
                let sy2 = fmt_num(c3.y - last.y, self.precision);
                let ax1 = fmt_num(c1.x, self.precision);
                let ay1 = fmt_num(c1.y, self.precision);
                let ax2 = fmt_num(c2.x, self.precision);
                let ay2 = fmt_num(c2.y, self.precision);
                let ax3 = fmt_num(c3.x, self.precision);
                let ay3 = fmt_num(c3.y, self.precision);
                let rel_cmd = format!("s{sx1} {sy1} {sx2} {sy2}");
                let abs_cmd = format!("C{ax1} {ay1} {ax2} {ay2} {ax3} {ay3}");
                if shorter(&rel_cmd, &abs_cmd) {
                    rel_cmd
                } else {
                    abs_cmd
                }
            } else {
                let ax1 = fmt_num(c1.x, self.precision);
                let ay1 = fmt_num(c1.y, self.precision);
                let ax2 = fmt_num(c2.x, self.precision);
                let ay2 = fmt_num(c2.y, self.precision);
                let ax3 = fmt_num(c3.x, self.precision);
                let ay3 = fmt_num(c3.y, self.precision);
                format!("C{ax1} {ay1} {ax2} {ay2} {ax3} {ay3}")
            };
            self.out.push_str(&cmd);
            self.cur = Some(c3);
            self.prev_c2 = Some(c2);
            return;
        }

        let cmd = if self.relative {
            let c1r = PointF64::new(c1.x - last.x, c1.y - last.y);
            let c2r = PointF64::new(c2.x - last.x, c2.y - last.y);
            let c3r = PointF64::new(c3.x - last.x, c3.y - last.y);
            let sx1 = fmt_num(c1r.x, self.precision);
            let sy1 = fmt_num(c1r.y, self.precision);
            let sx2 = fmt_num(c2r.x, self.precision);
            let sy2 = fmt_num(c2r.y, self.precision);
            let sx3 = fmt_num(c3r.x, self.precision);
            let sy3 = fmt_num(c3r.y, self.precision);
            let ax1 = fmt_num(c1.x, self.precision);
            let ay1 = fmt_num(c1.y, self.precision);
            let ax2 = fmt_num(c2.x, self.precision);
            let ay2 = fmt_num(c2.y, self.precision);
            let ax3 = fmt_num(c3.x, self.precision);
            let ay3 = fmt_num(c3.y, self.precision);
            let rel_cmd = format!("c{sx1} {sy1} {sx2} {sy2} {sx3} {sy3}");
            let abs_cmd = format!("C{ax1} {ay1} {ax2} {ay2} {ax3} {ay3}");
            if shorter(&rel_cmd, &abs_cmd) {
                rel_cmd
            } else {
                abs_cmd
            }
        } else {
            let ax1 = fmt_num(c1.x, self.precision);
            let ay1 = fmt_num(c1.y, self.precision);
            let ax2 = fmt_num(c2.x, self.precision);
            let ay2 = fmt_num(c2.y, self.precision);
            let ax3 = fmt_num(c3.x, self.precision);
            let ay3 = fmt_num(c3.y, self.precision);
            format!("C{ax1} {ay1} {ax2} {ay2} {ax3} {ay3}")
        };
        self.out.push_str(&cmd);
        self.cur = Some(c3);
        self.prev_c2 = Some(c2);
    }

    /// Emit a close-path.
    fn close(&mut self) {
        self.out.push('Z');
        self.cur = self.start;
        self.prev_c2 = None;
    }

    /// Finish and return the encoded path data.
    fn finish(self) -> String {
        self.out
    }
}

/// Reflect point `p` across `center`.
#[inline]
fn reflect(center: PointF64, p: PointF64) -> PointF64 {
    PointF64::new(2.0 * center.x - p.x, 2.0 * center.y - p.y)
}

/// Format a number with the given precision, applying the separator-before-negative rule.
fn fmt_num(value: f64, precision: Option<u32>) -> String {
    match precision {
        Some(p) => format!("{value:.p$}", p = p as usize),
        None => format!("{value}"),
    }
}

/// Join a list of number strings with spaces.
#[allow(dead_code)]
fn join_nums(nums: &[String]) -> String {
    nums.join(" ")
}

/// Pick the shorter of two encoded command strings.
#[inline]
fn shorter(a: &str, b: &str) -> bool {
    a.len() <= b.len()
}

/// Whether two floats are approximately equal (used for axis-alignment).
#[inline]
fn approx(a: f64, b: f64) -> bool {
    (a - b).abs() < 1e-6
}

/// Whether two points are approximately equal.
#[inline]
fn approx_pt(a: PointF64, b: PointF64) -> bool {
    approx(a.x, b.x) && approx(a.y, b.y)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::{Paint, SubPath};
    use crate::types::Color;

    fn subpath_line(a: PointF64, b: PointF64) -> SubPath {
        let mut sp = SubPath::new();
        sp.commands.push(PathCmd::MoveTo(a));
        sp.commands.push(PathCmd::LineTo(b));
        sp
    }

    #[test]
    fn fmt_num_rounds() {
        assert_eq!(fmt_num(1.2345, Some(2)), "1.23");
        assert_eq!(fmt_num(1.2345, None), "1.2345");
    }

    #[test]
    fn write_emits_svg_wrapper() {
        let mut doc = VectorDoc::new(10, 10);
        let sp = subpath_line(PointF64::new(0.0, 0.0), PointF64::new(5.0, 5.0));
        let mut mp = MultiPath::new();
        mp.push(sp);
        doc.shapes.push(Shape {
            paint: Paint::Solid(Color::new(255, 0, 0)),
            path: mp,
        });
        let svg = SvgWriter::default().write(&doc);
        assert!(svg.starts_with("<?xml"));
        assert!(svg.contains("<svg version=\"1.1\""));
        assert!(svg.contains("width=\"10\""));
        assert!(svg.contains("height=\"10\""));
        assert!(svg.ends_with("</svg>\n"));
        assert!(svg.contains("fill=\"#ff0000\""));
    }

    #[test]
    fn to_hex_string_format() {
        assert_eq!(Color::new(255, 0, 0).to_hex_string(), "#ff0000");
        assert_eq!(Color::new(16, 32, 64).to_hex_string(), "#102040");
    }
}
