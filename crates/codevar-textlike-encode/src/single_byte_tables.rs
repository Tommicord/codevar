//! Pointer tables for the legacy single-byte encodings defined by the
//! Encoding Standard (<https://encoding.spec.whatwg.org/>).
//!
//! Each table is the normative `index-<encoding>.txt` file shipped with the
//! standard, transcribed literally: entry `i` is the code point for the byte
//! `0x80 + i`, and `0` marks a pointer the standard leaves undefined, which
//! decodes to a replacement code point. Bytes `0x00..0x80` are not table
//! entries: they decode to the matching ASCII code point.
//!
//! Every table is injective, so the reverse lookup performed by
//! [`crate::single_byte::SingleByteEncoder`] always yields the standard's
//! "index pointer" (the first pointer that maps to the code point).

