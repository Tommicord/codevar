/// Unicode Grapheme Cluster Break property values (UAX #29 GB1-GB999).
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[must_use]
pub enum GraphemeClusterBreak {
    /// Any code point (catch-all).
    Other = 0,
    /// U+000D CARRIAGE RETURN (CR).
    CR = 1,
    /// U+000A LINE FEED (LF).
    LF = 2,
    /// Control characters (general category Control, Line_Separator, Paragraph_Separator, Format, etc.).
    Control = 3,
    /// Extend characters (General_Category=Nonspacing_Mark, Enclosing_Mark, Join_Control, and some Spacing_Marks needed for canonical equivalence).
    Extend = 4,
    /// U+200D ZERO WIDTH JOINER.
    ZWJ = 5,
    /// Regional Indicator symbols (U+1F1E6..U+1F1FF).
    RegionalIndicator = 6,
    /// Indic_Syllabic_Category=Consonant_Preceding_Repha or Consonant_Prefixed, or Prepended_Concatenation_Mark=Yes.
    Prepend = 7,
    /// SpacingMark (General_Category=Spacing_Mark, with specific exceptions).
    SpacingMark = 8,
    /// Hangul ChoSeong (L type).
    L = 9,
    /// Hangul JungSeong (V type).
    V = 10,
    /// Hangul JongSeong (T type).
    T = 11,
    /// Hangul LV (LV type).
    LV = 12,
    /// Hangul LVT (LVT type).
    LVT = 13,
}

/// Unicode Word Break property values (UAX #29 WB1-WB999).
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[must_use]
pub enum WordBreak {
    /// Any code point (catch-all).
    Other = 0,
    /// U+000D CARRIAGE RETURN (CR).
    CR = 1,
    /// U+000A LINE FEED (LF).
    LF = 2,
    /// Newline characters (Line Tabulation, Form Feed, etc.).
    Newline = 3,
    /// Extend characters.
    Extend = 4,
    /// Format characters (excluding ZWSP, ZWNJ, ZWJ).
    Format = 5,
    /// U+200D ZERO WIDTH JOINER.
    ZWJ = 6,
    /// Regional Indicator symbols (U+1F1E6..U+1F1FF).
    RegionalIndicator = 7,
    /// WSegSpace: General_Category=Zs and not Linebreak=Glue.
    WSegSpace = 8,
    /// Alphabetic characters (ALetter): Unicode Alphabetic property, excluding Hebrew/IDEographic.
    ALetter = 9,
    /// Hebrew_Letter.
    HebrewLetter = 10,
    /// Numeric digits and numeric-related.
    Numeric = 11,
    /// Katakana script characters.
    Katakana = 12,
    /// ExtendNumLet: General_Category=Connector_Punctuation or U+202F NARROW_NO_BREAK_SPACE.
    ExtendNumLet = 13,
    /// MidLetter: various punctuation marks.
    MidLetter = 14,
    /// MidNumLet: MidNumLet or Single_Quote.
    MidNumLet = 15,
    /// MidNum: various numeric-related marks.
    MidNum = 16,
    /// Single_Quote: U+0027 APOSTROPHE.
    SingleQuote = 17,
    /// Double_Quote: U+0022 QUOTATION MARK.
    DoubleQuote = 18,
}

/// Unicode Sentence Break property values (UAX #29 SB1-SB998).
#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[must_use]
pub enum SentenceBreak {
    /// Any code point (catch-all).
    Other = 0,
    /// U+000D CARRIAGE RETURN (CR).
    CR = 1,
    /// U+000A LINE FEED (LF).
    LF = 2,
    /// Sep: paragraph separators.
    Sep = 3,
    /// Extend characters.
    Extend = 4,
    /// Format characters.
    Format = 5,
    /// Sp: spaces.
    Sp = 6,
    /// Lowercase letter terminators context.
    Lower = 7,
    /// Uppercase letter terminators context.
    Upper = 8,
    /// Other Letter: OLetter.
    OLetter = 9,
    /// Numeric.
    Numeric = 10,
    /// ATerm: sentence terminators (period, exclamation, question mark).
    ATerm = 11,
    /// STerm: secondary sentence terminators.
    STerm = 12,
    /// Close: closing brackets/quotes.
    Close = 13,
    /// SContinue: continue after sentence break context.
    SContinue = 14,
}

/// Unicode Indic Conjunct Break property values (UCD DerivedCoreProperties).
