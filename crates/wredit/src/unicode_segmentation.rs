#[inline]
#[must_use]
pub fn next_grapheme_boundary(code_points: &[u32], mut index: usize) -> usize {
    if index >= code_points.len() {
        return code_points.len();
    }
    while index < code_points.len() && !is_grapheme_boundary(code_points, index) {
        index += 1;
    }
    index.min(code_points.len())
}

#[inline]
#[must_use]
pub fn prev_grapheme_boundary(code_points: &[u32], mut index: usize) -> usize {
    if index == 0 {
        return 0;
    }
    while index > 0 && !is_grapheme_boundary(code_points, index) {
        index -= 1;
    }
    index
}

