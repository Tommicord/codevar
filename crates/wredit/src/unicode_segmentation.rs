// Convenience: decode &str into code points (allocates Vec<u32>)
// ---------------------------------------------------------------------------

/// Decode a UTF-8 string into a vector of Unicode code points.
/// Used for str-based segmentation when no_std is not required.
pub fn decode_str_to_code_points(s: &str) -> Vec<u32> {
    s.chars().map(|c| c as u32).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_gcb_cr_lf() {
        // GB3: CR LF should not break
        let cp = [0x000D, 0x000A]; // CR LF
        assert!(!is_grapheme_boundary(&cp, 1));
    }

    #[test]
    fn test_gcb_extend() {
        // Combining accent after base: should not break before Extend
        let cp = [0x0041, 0x0300]; // A + combining grave
        // Boundary after A (index 1): prev=A, next=Extend -> GB9 says no break
        assert!(!is_grapheme_boundary(&cp, 1));
    }

    #[test]
    fn test_gcb_hangul_l() {
        // Hangul L type: GB6 says L × (L | V | LV | LVT) = no break
        // Each Hangul syllable component
        let cp = [0x1100, 0x1161]; // ᄀ ᅡ (Hangul Jamo L + V)
        // This should not break between L and V
        assert!(!is_grapheme_boundary(&cp, 1));
    }

    #[test]
    fn test_wb_cr_lf() {
        // WB3: Do not break within CRLF.
        let cp = [0x000D, 0x000A];
        assert!(!is_word_boundary(&cp, 1));
    }

    #[test]
    fn test_sb_cr_lf() {
        // SB3: Do not break within CRLF.
        let cp = [0x000D, 0x000A];
        assert!(!is_sentence_boundary(&cp, 1));
    }

    #[test]
    fn test_next_prev_grapheme() {
        // Basic ASCII: each char is its own grapheme
        let cp = decode_str_to_code_points("hello");
        assert_eq!(next_grapheme_position(&cp, 0), 1);
        assert_eq!(prev_grapheme_position(&cp, 1), 0);
        assert_eq!(next_grapheme_position(&cp, 4), 5);
        assert_eq!(prev_grapheme_position(&cp, 5), 4);
    }

    #[test]
    fn test_gcb_combining() {
        // A + combining grave should be one grapheme cluster
        let cp = [0x0041, 0x0300]; // A + U+0300 COMBINING GRAVE ACCENT
        // The grapheme cluster is: position 0 (A) + position 1 (combine)
        // Boundary at index 1 should NOT break (Extend before anything)
        // Boundary at index 2 (past end) should be a break
        assert!(!is_grapheme_boundary(&cp, 1)); // no break before Extend
        assert!(is_grapheme_boundary(&cp, 2)); // past end -> break
    }
}
