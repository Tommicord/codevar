// ---------------------------------------------------------------------------
// Helper: binary search lookup for property tables
// ---------------------------------------------------------------------------

#[inline]
fn gcp_lookup(table: &[(u32, u32, u8)], cp: u32) -> u8 {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (start, end, val) = table[mid];
        if cp < start {
            hi = mid;
        } else if cp > end {
            lo = mid + 1;
        } else {
            return val;
        }
    }
    0 // Other
}

#[inline]
fn ep_lookup(table: &[(u32, u32)], cp: u32) -> bool {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (start, end) = table[mid];
        if cp < start {
            hi = mid;
        } else if cp > end {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    false
}

