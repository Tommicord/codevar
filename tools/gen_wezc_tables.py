# Generate the WEZC squash/stretch tables for the Rust codec.
#
# The two tables are inside the prediction path of both the encoder and the
# decoder, so they must be byte-identical on every machine that ever touches a
# stream. Generating them at build time would make the stream depend on the
# host libm, which is why this script exists: run it once, commit the result.
#
# The formulas are the ones in tools/wezc.py, so the Rust model and the
# prototype agree bit for bit.
#
# Usage:
#   python3 tools/gen_wezc_tables.py > crates/wredit-werc/src/tables_data.rs
"""Print the Rust source for the WEZC squash and stretch tables."""

import math

#: logit domain, shared by the squash table and the mixer clamp.
LOGIT_MIN = -2047
LOGIT_MAX = 2047

#: probability domain for the stretch table: 12-bit, never 0 or 4096.
P_MIN = 1
P_MAX = 4095

#: widest logit band in which squash and stretch are exact inverses.
INVERSE_BAND = 384


def squash():
    """logit -> 12-bit probability, one entry per integer logit."""
    return [
        max(P_MIN, min(P_MAX, int(round(4096.0 / (1.0 + math.exp(-i / 128.0))))))
        for i in range(LOGIT_MIN, LOGIT_MAX + 1)
    ]


def stretch():
    """12-bit probability -> logit, indexed by the probability."""
    return [0] + [
        max(LOGIT_MIN, min(LOGIT_MAX, int(round(128.0 * math.log(p / (4096.0 - p))))))
        for p in range(P_MIN, P_MAX + 1)
    ]


def emit(name, values, doc):
    """Print one `static` array, sixteen values to a line."""
    print(doc)
    print("#[rustfmt::skip]")
    print(f"pub(crate) static {name}: [i16; {len(values)}] = [")
    for start in range(0, len(values), 16):
        row = values[start : start + 16]
        print("    " + ", ".join(str(v) for v in row) + ",")
    print("];")
    print()


def check(sq, st):
    """Verify the tables before committing them.

    Both are inside the prediction path, so a wrong value silently changes the
    decoder's output. Monotonicity and the domain bounds are what the mixer
    relies on. squash and stretch are only approximate inverses: a 12-bit
    probability has a little end of its own, so |logit| > 384 cannot be
    recovered from it, which is why the inverse is checked in that band only.
    """
    assert len(sq) == 4095 and len(st) == 4096
    assert all(1 <= v <= 4095 for v in sq)
    assert all(-2047 <= v <= 2047 for v in st)
    assert all(b >= a for a, b in zip(sq, sq[1:])), "squash is not monotonic"
    # st[0] is a placeholder for the unused probability 0.
    assert all(b >= a for a, b in zip(st[1:], st[2:])), "stretch is not monotonic"
    for i in range(-INVERSE_BAND, INVERSE_BAND + 1):
        assert st[sq[i - LOGIT_MIN]] == i, f"not inverse at {i}"


def main():
    sq, st = squash(), stretch()
    check(sq, st)
    header = [
        "// Copyright 2026 Codevar Project",
        '// Licensed under the Apache License, Version 2.0 (the',
        '// "License"); you may not use this file except in',
        "// compliance with the License. You may obtain a copy of the",
        "// License at",
        "//",
        "//   https://www.apache.org/licenses/LICENSE-2.0",
        "//",
        "// Unless required by applicable law or agreed to in",
        "// writing, software distributed under the License is",
        '// distributed on an "AS IS" BASIS, WITHOUT WARRANTIES OR',
        "// CONDITIONS OF ANY KIND, either express or implied. See the",
        "// License for the specific language governing permissions and",
        "// limitations under the License.",
        "",
        "//! Squash and stretch tables for the model, generated once and",
        "//! committed so every build agrees on the same 12-bit domain.",
        "//! Regenerate with `python3 tools/gen_wezc_tables.py`.",
        "",
    ]
    for line in header:
        print(line)
    print("// Generated by tools/gen_wezc_tables.py. Do not edit by hand.")
    print("//\n// Squash: logit index [-2047..2047] -> 12-bit probability.")
    emit(
        "SQ",
        sq,
        "/// `squash`: index `logit + 2047` to get a 12-bit probability.",
    )
    emit(
        "ST",
        st,
        "/// `stretch`: index a 12-bit probability to get a logit.",
    )


main()
